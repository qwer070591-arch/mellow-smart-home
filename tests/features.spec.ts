test('手機排程滾輪支援觸控拖曳與鍵盤調整', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })
  const page = await context.newPage()
  await page.goto(base)
  await page.getByRole('button', { name: '開啟排程' }).tap()
  await page.getByRole('button', { name: /執行時間 .*調整時間/ }).tap()
  await expect(page.getByRole('dialog', { name: '執行時間選擇器' })).toHaveCSS('transform', 'none')
  const hours = page.getByRole('listbox', { name: '執行小時' })
  const box = await hours.boundingBox()
  expect(box).not.toBeNull()
  const touch = await context.newCDPSession(page)
  const x = box!.x + box!.width / 2
  const y = box!.y + box!.height / 2
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] })
  for (const offset of [20, 45, 70, 88]) await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: y - offset }] })
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  await expect(hours.getByRole('option', { name: '09' })).toHaveAttribute('aria-selected', 'true')
  const minutes = page.getByRole('listbox', { name: '執行分鐘' })
  await minutes.focus()
  await minutes.press('ArrowDown')
  await expect(minutes.getByRole('option', { name: '31' })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: '確定' }).tap()
  await expect(page.getByRole('button', { name: /執行時間 09:31/ })).toBeVisible()
  await context.close()
})

test('玻璃選單支援鍵盤與外部點擊，排程面板回復焦點', async ({ page }) => {
  await page.goto(base)
  const trigger = page.getByRole('button', { name: '開啟排程' })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '排程管理' })
  const room = dialog.getByRole('button', { name: /^房間：/ })
  await room.focus()
  await room.press('ArrowDown')
  const options = dialog.getByRole('listbox', { name: '房間' })
  await expect(options).toBeVisible()
  await options.getByRole('option', { name: '客廳' }).press('ArrowDown')
  await expect(options.getByRole('option', { name: '主臥' })).toBeFocused()
  await options.getByRole('option', { name: '主臥' }).press('Enter')
  await expect(room).toHaveAccessibleName('房間：主臥')
  await room.click()
  await options.getByRole('option', { name: '主臥' }).press('Escape')
  await expect(options).toHaveCount(0)
  await expect(room).toBeFocused()
  await page.locator('.alarm-sheet-layer .time-sheet-backdrop').click({ position: { x: 4, y: 4 } })
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

