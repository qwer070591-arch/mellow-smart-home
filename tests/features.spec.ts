  await expect(page.locator('.lighting-card input[type=range]').first()).toHaveValue('0')
  await page.getByRole('tab', { name: '客廳' }).click()
  await expect(page.locator('.lighting-card input[type=range]').first()).toHaveValue('37')
  await page.reload()
  await expect(page.locator('.lighting-card input[type=range]').first()).toHaveValue('37')
